
function dist_mat = state_distances(P)
% Compute normalised distance matrix between US states.
% Uses approximate lat/lon centroids from a hard-coded table.
% Distances are normalised so mean(off-diagonal) = 1.
    J = P.J;
    centroids = [ ...
        32.8, -86.8;   64.2, -152.5;  34.3, -111.1;  34.8,  -92.2; ...
        36.8, -119.4;  39.1, -105.4;  41.6,  -72.7;  39.0,  -75.5; ...
        38.9,  -77.0;  28.7,  -82.5;  32.2,  -83.4;  20.3, -156.4; ...
        44.4, -114.5;  40.0,  -89.2;  40.3,  -86.1;  42.0,  -93.5; ...
        38.5,  -98.4;  37.8,  -84.3;  31.2,  -91.8;  45.4,  -69.2; ...
        39.1,  -76.8;  42.3,  -71.8;  44.3,  -85.4;  46.4,  -93.2; ...
        32.7,  -89.7;  38.5,  -92.6;  47.0, -110.5;  41.5,  -99.9; ...
        39.3, -117.1;  43.7,  -71.6;  40.1,  -74.7;  34.5, -106.2; ...
        43.0,  -75.5;  35.5,  -79.4;  47.5, -100.5;  40.4,  -82.8; ...
        35.6,  -96.9;  44.0, -120.6;  40.9,  -77.8;  41.7,  -71.5; ...
        33.9,  -80.9;  44.4,  -99.9;  35.9,  -86.4;  31.5,  -99.3; ...
        39.5, -111.1;  44.0,  -72.7;  37.8,  -78.7;  47.7, -120.7; ...
        38.9,  -80.5;  44.6,  -89.8;  43.2, -107.5];
    dist_mat = zeros(J, J);
    for j = 1:J
        for l = 1:J
            if j ~= l
                dlat = (centroids(j,1) - centroids(l,1)) * pi/180;
                dlon = (centroids(j,2) - centroids(l,2)) * pi/180;
                a    = sin(dlat/2)^2 + cos(centroids(j,1)*pi/180) * ...
                       cos(centroids(l,1)*pi/180) * sin(dlon/2)^2;
                dist_mat(j,l) = 6371 * 2 * atan2(sqrt(a), sqrt(1-a));
            end
        end
    end
    off_diag = dist_mat(dist_mat > 0);
    dist_mat = dist_mat / mean(off_diag);
end